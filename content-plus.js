  function getTopic(subjectId, topicId) {
    const subject = getSubject(subjectId);
    if (!subject) {
      return null;
    }

    return subject.topics.find((topic) => topic.id === topicId) || null;
  }

  function extendSubject(subjectId, patch) {
    const subject = getSubject(subjectId);
    if (!subject) {
      return;
    }

    Object.entries(patch).forEach(([key, value]) => {
      if (listKeys.has(key)) {
        subject[key] = [...(subject[key] || []), ...value];
        return;
      }

      subject[key] = value;
    });
  }

  function extendTopic(subjectId, topicId, patch) {
    const topic = getTopic(subjectId, topicId);
    if (!topic) {
      return;
    }

    Object.entries(patch).forEach(([key, value]) => {
      if (listKeys.has(key)) {
        topic[key] = [...(topic[key] || []), ...value];
        return;
      }

      topic[key] = value;
    });
  }

  function pushTopics(subjectId, topics) {
    const subject = getSubject(subjectId);
    if (!subject) {
      return;
    }

    subject.topics.push(...topics);
  }

